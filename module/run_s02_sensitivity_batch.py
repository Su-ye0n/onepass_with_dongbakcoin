
"""Batch runner for S02 conditional auto-topup sensitivity.

Reads the scenario manifest generated by s02_sensitivity.py.

Default: validate inputs only.
--run requires an explicit v3.4 data confirmation.

No database writes or real payments.
"""

from __future__ import annotations

import argparse
import csv
import json
from collections import Counter
from decimal import Decimal, ROUND_HALF_UP
from pathlib import Path
from types import SimpleNamespace

import run_s02_auto_topup as runner
import simulate_original_v2 as sim


ROOT = Path(__file__).resolve().parent
INPUT_DIR = ROOT / "s02_sensitivity_inputs"
OUTPUT_DIR = ROOT / "s02_sensitivity_results"

EXPECTED_USERS = 240
EXPECTED_MEMBERS = 111
EXPECTED_TRANSACTIONS = 7540
EXPECTED_V34_AMOUNT = 217449500

EXPECTED_RATES = (
    Decimal("25"),
    Decimal("38.4"),
    Decimal("50"),
)

EXPECTED_FUNDING = (
    100000,
    180000,
    300000,
)

PROFILE_FILE = (
    ROOT / "v2_output" / "sim_user_profile_v2.csv"
)


def rate_label(value):
    """Convert a consent rate to a stable scenario ID."""
    rate = Decimal(str(value))

    text = format(rate, "f")

    if "." in text:
        text = text.rstrip("0").rstrip(".")

    return text.replace(".", "P")


def make_id(rate, funding):
    return (
        f"S02_C{rate_label(rate)}_F{funding}"
    )


def expected_count(rate):
    value = (
        Decimal(EXPECTED_MEMBERS)
        * rate
        / Decimal("100")
    )
    return int(
        value.quantize(
            Decimal("1"),
            rounding=ROUND_HALF_UP,
        )
    )


def read_profiles():
    with PROFILE_FILE.open(
        encoding="utf-8-sig", newline=""
    ) as f:
        rows = list(csv.DictReader(f))

    profiles = {}

    for row in rows:
        uid = row["user_id"].strip()

        if not uid or uid in profiles:
            raise ValueError(
                f"INVALID_PROFILE_USER:{uid}"
            )

        profiles[uid] = row

    if len(profiles) != EXPECTED_USERS:
        raise ValueError("PROFILE_COUNT_MISMATCH")

    members = {
        uid
        for uid, p in profiles.items()
        if p["dongbaek_usage_level"]
        != "NON_MEMBER"
    }

    if len(members) != EXPECTED_MEMBERS:
        raise ValueError("MEMBER_COUNT_MISMATCH")

    return profiles, members


def load_manifest(input_dir):
    path = input_dir / "manifest.json"

    with path.open(encoding="utf-8") as f:
        manifest = json.load(f)

    if manifest.get("scenario_count") != 9:
        raise ValueError(
            "INVALID_MANIFEST_SCENARIO_COUNT"
        )

    if manifest.get("user_count") != EXPECTED_USERS:
        raise ValueError(
            "INVALID_MANIFEST_USER_COUNT"
        )

    if (
        manifest.get("dongbaek_member_count")
        != EXPECTED_MEMBERS
    ):
        raise ValueError(
            "INVALID_MANIFEST_MEMBER_COUNT"
        )

    if manifest.get("nonmember_count") != 129:
        raise ValueError(
            "INVALID_MANIFEST_NONMEMBER_COUNT"
        )

    if manifest.get("nested_consent_cohorts") is not True:
        raise ValueError(
            "CONSENT_NESTING_NOT_CONFIRMED"
        )

    entries = manifest.get("scenarios")

    if not isinstance(entries, list) or len(entries) != 9:
        raise ValueError(
            "INVALID_MANIFEST_ENTRIES"
        )

    return manifest


def validate_inputs(input_dir):
    manifest = load_manifest(input_dir)
    profiles, members = read_profiles()

    entries = manifest["scenarios"]
    seen_ids = set()
    consent_sets = {}
    scenarios = []

    for entry in entries:
        rate = Decimal(
            str(entry["consent_rate_assumption_pct"])
        )
        funding = int(
            entry["funding_per_consent_user_won"]
        )

        if rate not in EXPECTED_RATES:
            raise ValueError(
                f"UNEXPECTED_CONSENT_RATE:{rate}"
            )

        if funding not in EXPECTED_FUNDING:
            raise ValueError(
                f"UNEXPECTED_FUNDING:{funding}"
            )

        sid = make_id(rate, funding)

        if entry["scenario_id"] != sid:
            raise ValueError(
                f"SCENARIO_ID_MISMATCH:{sid}"
            )

        if sid in seen_ids:
            raise ValueError(
                f"DUPLICATE_SCENARIO:{sid}"
            )

        seen_ids.add(sid)

        filename = f"{sid}.csv"

        if entry["input_file"] != filename:
            raise ValueError(
                f"FILENAME_MISMATCH:{sid}"
            )

        path = input_dir / filename
        assumptions = runner.load_assumptions(path)

        if set(assumptions) != set(profiles):
            raise ValueError(
                f"USER_COVERAGE_MISMATCH:{sid}"
            )

        consenting = {
            uid
            for uid, values in assumptions.items()
            if values["consent"]
        }

        if not consenting.issubset(members):
            raise ValueError(
                f"NONMEMBER_CONSENT:{sid}"
            )

        count = expected_count(rate)

        if len(consenting) != count:
            raise ValueError(
                f"CONSENT_COUNT_MISMATCH:{sid}"
            )

        if (
            int(entry["consenting_user_count"])
            != count
        ):
            raise ValueError(
                f"MANIFEST_CONSENT_COUNT:{sid}"
            )

        if (
            int(entry["total_assumed_funding_won"])
            != count * funding
        ):
            raise ValueError(
                f"MANIFEST_FUNDING_TOTAL:{sid}"
            )

        for uid, values in assumptions.items():
            expected_funding = (
                funding if uid in consenting else 0
            )

            if (
                values["funding_balance_won"]
                != expected_funding
            ):
                raise ValueError(
                    f"FUNDING_MISMATCH:{sid}:{uid}"
                )

        consent_sets[(rate, funding)] = consenting

        scenarios.append({
            "scenario_id": sid,
            "rate": rate,
            "funding": funding,
            "consenting_users": count,
            "input_path": path,
        })

    expected_ids = {
        make_id(rate, funding)
        for rate in EXPECTED_RATES
        for funding in EXPECTED_FUNDING
    }

    if seen_ids != expected_ids:
        raise ValueError(
            "MISSING_OR_EXTRA_SCENARIOS"
        )

    # Same consent cohort across funding levels.
    for rate in EXPECTED_RATES:
        first = consent_sets[
            (rate, EXPECTED_FUNDING[0])
        ]

        for funding in EXPECTED_FUNDING[1:]:
            if consent_sets[(rate, funding)] != first:
                raise ValueError(
                    f"CONSENT_COHORT_CHANGED:{rate}"
                )

    # Higher consent rates retain lower-rate users.
    for funding in EXPECTED_FUNDING:
        previous = set()

        for rate in EXPECTED_RATES:
            current = consent_sets[(rate, funding)]

            if not previous.issubset(current):
                raise ValueError(
                    f"CONSENT_NESTING_FAILED:{rate}"
                )

            previous = current

    scenarios.sort(
        key=lambda s: (s["rate"], s["funding"])
    )

    print("=== S02 BATCH INPUT VALIDATION ===")
    print("Users:", len(profiles))
    print("Dongbaek members:", len(members))
    print("Scenarios:", len(scenarios))

    for s in scenarios:
        print(
            s["scenario_id"],
            "| consenting:",
            s["consenting_users"],
            "| funding:",
            s["funding"],
        )

    print("CONSENT NESTING: PASSED")
    print("SCENARIO INPUTS: PASSED")
    print("SIMULATION: NOT EXECUTED")

    return scenarios


def verify_v34_source():
    """Check the transaction file used by the simulator."""

    grouped = sim.read_transactions(sim.SOURCE)

    user_count = len(grouped)
    transactions = [
        tx
        for txs in grouped.values()
        for tx in txs
    ]

    tx_ids = [
        tx["transaction_id"] for tx in transactions
    ]

    total = sum(
        int(tx["amount_won"])
        for tx in transactions
    )

    if user_count != EXPECTED_USERS:
        raise ValueError(
            f"V34_USER_COUNT_MISMATCH:{user_count}"
        )

    if len(transactions) != EXPECTED_TRANSACTIONS:
        raise ValueError(
            "V34_TRANSACTION_COUNT_MISMATCH:"
            f"{len(transactions)}"
        )

    if len(tx_ids) != len(set(tx_ids)):
        raise ValueError(
            "V34_DUPLICATE_TRANSACTION_ID"
        )

    if total != EXPECTED_V34_AMOUNT:
        raise ValueError(
            "V34_AMOUNT_MISMATCH:"
            f"actual={total}:"
            f"expected={EXPECTED_V34_AMOUNT}"
        )

    print("\n=== V3.4 SOURCE VERIFICATION ===")
    print("Users:", user_count)
    print("Transactions:", len(transactions))
    print("Amount:", total)
    print("V3.4 TRANSACTION SOURCE: PASSED")


def write_csv(path, rows):
    if not rows:
        raise ValueError("EMPTY_BATCH_RESULTS")

    fields = list(rows[0])

    with path.open(
        "w",
        newline="",
        encoding="utf-8-sig",
    ) as f:
        writer = csv.DictWriter(
            f,
            fieldnames=fields,
        )

        writer.writeheader()
        writer.writerows(rows)


def execute_batch(scenarios, output_dir, args):
    targets = [
        output_dir / s["scenario_id"]
        for s in scenarios
    ] + [
        output_dir / "sensitivity_summary.csv",
        output_dir / "sensitivity_summary.json",
    ]

    existing = [
        str(p) for p in targets if p.exists()
    ]

    if existing:
        raise FileExistsError(
            "OUTPUT_ALREADY_EXISTS:"
            + ", ".join(existing[:5])
        )

    output_dir.mkdir(
        parents=True,
        exist_ok=True,
    )

    results = []

    summary_fields = [
        "user_count",
        "consenting_users",
        "transaction_count",
        "transaction_amount_won",
        "assigned_count",
        "unresolved_count",
        "dongbaek_count",
        "bnk_count",
        "estimated_benefit_won",
        "auto_topup_total_won",
        "auto_topup_event_count",
    ]

    for index, scenario in enumerate(
        scenarios, start=1
    ):
        sid = scenario["scenario_id"]

        print(
            f"\n=== RUN {index}/9: {sid} ===",
            flush=True,
        )

        run_args = SimpleNamespace(
            assumptions=scenario["input_path"],
            output=output_dir / sid,
            limit=None,
            min_topup=args.min_topup,
            per_topup_cap=args.per_topup_cap,
            monthly_cap=args.monthly_cap,
            wallet_cap=args.wallet_cap,
        )

        assumptions = runner.load_assumptions(
            run_args.assumptions
        )

        summary = runner.run_s02(
            run_args,
            assumptions,
        )

        if not isinstance(summary, dict):
            raise ValueError(
                f"MISSING_SCENARIO_SUMMARY:{sid}"
            )

        for field in summary_fields:
            if field not in summary:
                raise ValueError(
                    f"MISSING_SUMMARY_FIELD:{sid}:{field}"
                )

        if (
            summary["user_count"] != EXPECTED_USERS
            or summary["transaction_count"]
            != EXPECTED_TRANSACTIONS
            or summary["transaction_amount_won"]
            != EXPECTED_V34_AMOUNT
        ):
            raise ValueError(
                f"SCENARIO_POPULATION_MISMATCH:{sid}"
            )

        if (
            summary["consenting_users"]
            != scenario["consenting_users"]
        ):
            raise ValueError(
                f"CONSENT_SUMMARY_MISMATCH:{sid}"
            )

        results.append({
            "scenario_id": sid,
            "consent_rate_pct": float(
                scenario["rate"]
            ),
            "funding_per_user_won": scenario["funding"],
            **{
                field: summary[field]
                for field in summary_fields
            },
        })

    summary_csv = (
        output_dir / "sensitivity_summary.csv"
    )

    write_csv(summary_csv, results)

    (output_dir / "sensitivity_summary.json").write_text(
        json.dumps(
            {
                "experiment": (
                    "S02_AUTO_TOPUP_SENSITIVITY_V34"
                ),
                "data_version": "v3.4",
                "scenario_count": 9,
                "simulation_only": True,
                "results": results,
            },
            ensure_ascii=False,
            indent=2,
        ),
        encoding="utf-8",
    )

    print("\nBATCH SIMULATION: COMPLETE")
    print("Saved:", output_dir)


def main():
    parser = argparse.ArgumentParser()

    parser.add_argument(
        "--input-dir",
        type=Path,
        default=INPUT_DIR,
    )

    parser.add_argument(
        "--output-dir",
        type=Path,
        default=OUTPUT_DIR,
    )

    parser.add_argument(
        "--min-topup",
        type=int,
        default=10000,
    )

    parser.add_argument(
        "--per-topup-cap",
        type=int,
        default=100000,
    )

    parser.add_argument(
        "--monthly-cap",
        type=int,
        default=300000,
    )

    parser.add_argument(
        "--wallet-cap",
        type=int,
        default=500000,
    )

    parser.add_argument(
        "--data-v34-confirmed",
        action="store_true",
        help=(
            "Confirm that the data team has updated "
            "the source transactions and merchant data."
        ),
    )

    mode = parser.add_mutually_exclusive_group()

    mode.add_argument(
        "--validate-only",
        action="store_true",
    )

    mode.add_argument(
        "--run",
        action="store_true",
    )

    args = parser.parse_args()

    runner.validate_policy_args(args)

    scenarios = validate_inputs(args.input_dir)

    if not args.run:
        print("\nBATCH READY. No simulation run.")
        return

    if not args.data_v34_confirmed:
        raise ValueError(
            "V34_DATA_CONFIRMATION_REQUIRED"
        )

    # Data upload alone does not guarantee that the
    # simulator's local transaction source is updated.
    verify_v34_source()

    execute_batch(
        scenarios,
        args.output_dir,
        args,
    )


if __name__ == "__main__":
    main()
